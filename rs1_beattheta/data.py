"""Step 1 - Synthetic dataset.

Every training clip is generated by code. Five texture families are rendered with randomized
parameters (pitch, detuning, slow modulation, noise colour, filtering) so that no two clips are alike.
"""
import numpy as np
import scipy.signal as sps
import torch

SR = 8000            # sample rate used by the model
CHUNK = 16384        # clip length in samples (2.048 s)
TEXTURES = ["warm_pad", "deep_drone", "ocean_swell", "soft_rain", "crystal_pad"]
TARGET_RMS = 0.2     # every clip is normalised to this level


def _normalise(x, rms=TARGET_RMS):
    x = np.asarray(x, dtype=np.float64)
    x = x - x.mean()
    x = x * (rms / (np.sqrt(np.mean(x ** 2)) + 1e-9))
    return np.clip(x, -1, 1).astype(np.float32)


def _time(n):
    return np.arange(n) / SR


def _lowpass(x, cutoff, order=2):
    return sps.sosfilt(sps.butter(order, cutoff, "low", fs=SR, output="sos"), x)


def _coloured_noise(n, rng, beta):
    """Noise with a 1/f^beta power spectrum (beta=1 pink, beta=2 brown)."""
    spec = np.fft.rfft(rng.standard_normal(n))
    f = np.fft.rfftfreq(n, 1 / SR)
    f[0] = f[1]
    return np.fft.irfft(spec / f ** (beta / 2), n)


def _slow_lfo(n, rng, lo, hi, depth):
    rate, phase = rng.uniform(lo, hi), rng.uniform(0, 2 * np.pi)
    return 1 - depth + depth * 0.5 * (1 + np.sin(2 * np.pi * rate * _time(n) + phase))


def warm_pad(n, rng):
    """Stack of detuned harmonics with slow amplitude drift, low-passed."""
    root, y = rng.uniform(55, 98), np.zeros(n)
    for ratio, amp in zip([1, 1.5, 2, 3, 4, 5], [1, .6, .5, .3, .2, .1]):
        for _ in range(3):
            freq = root * ratio * 2 ** (rng.uniform(-9, 9) / 1200)
            y += amp * _slow_lfo(n, rng, .05, .25, .5) * np.sin(2 * np.pi * freq * _time(n) + rng.uniform(0, 6.28))
    return _normalise(_lowpass(y, 1500))


def deep_drone(n, rng):
    """Low fundamental with gentle vibrato, harmonics and brown-noise undertone."""
    f0 = rng.uniform(32, 52)
    freq = f0 * (1 + 0.003 * np.sin(2 * np.pi * rng.uniform(.1, .3) * _time(n)))
    phase, y = 2 * np.pi * np.cumsum(freq) / SR, np.zeros(n)
    for h in range(1, 8):
        y += (1 / h ** 1.2) * np.sin(h * phase + rng.uniform(0, 6.28))
    noise = _lowpass(_coloured_noise(n, rng, 2), 300)
    y += 0.4 * noise / (np.std(noise) + 1e-9)
    return _normalise(_lowpass(y, 700))


def ocean_swell(n, rng):
    """Brown plus pink noise shaped by a slow swell envelope, band-passed."""
    x = _coloured_noise(n, rng, 2) + 0.7 * _coloured_noise(n, rng, 1)
    x = x / (np.std(x) + 1e-9)
    envelope = 0.25 + 0.75 * _slow_lfo(n, rng, .06, .16, 1.0)
    sos = sps.butter(2, [50, 2800], "band", fs=SR, output="sos")
    return _normalise(sps.sosfilt(sos, x * envelope))


def soft_rain(n, rng):
    """Band-limited pink noise with sparse soft droplets."""
    x = _coloured_noise(n, rng, 1)
    x = sps.sosfilt(sps.butter(2, [400, 3600], "band", fs=SR, output="sos"), x / (np.std(x) + 1e-9))
    drops = (rng.random(n) < 25 / SR) * rng.uniform(0.5, 2.0, n)
    drops = sps.sosfilt(sps.butter(2, [1500, 3500], "band", fs=SR, output="sos"), drops)
    return _normalise(x + 6.0 * drops)


def crystal_pad(n, rng):
    """Higher register partials with slow shimmer."""
    root, y = rng.uniform(196, 330), np.zeros(n)
    for ratio in [1, 2, 3, 4, 5, 6]:
        for _ in range(2):
            freq = root * ratio * 2 ** (rng.uniform(-6, 6) / 1200)
            if freq < SR / 2 - 400:
                y += (1 / ratio ** 0.8) * _slow_lfo(n, rng, .1, .5, .7) * np.sin(2 * np.pi * freq * _time(n) + rng.uniform(0, 6.28))
    return _normalise(_lowpass(y, 3500))


TEXTURE_FUNCS = dict(warm_pad=warm_pad, deep_drone=deep_drone, ocean_swell=ocean_swell,
                     soft_rain=soft_rain, crystal_pad=crystal_pad)


def reference_clips(texture, n, seed):
    """Fresh procedural clips of one texture (used for evaluation)."""
    return [TEXTURE_FUNCS[texture](CHUNK, np.random.default_rng(seed + i)) for i in range(n)]


def build_dataset(n_per_class, seed):
    """Return (clips [N,1,CHUNK] float32, labels [N] long) for all textures."""
    xs, ys = [], []
    for ci, name in enumerate(TEXTURES):
        for i in range(n_per_class):
            rng = np.random.default_rng(seed * 100003 + ci * 10007 + i)
            xs.append(TEXTURE_FUNCS[name](CHUNK, rng))
            ys.append(ci)
    return torch.from_numpy(np.stack(xs))[:, None, :], torch.tensor(ys, dtype=torch.long)
